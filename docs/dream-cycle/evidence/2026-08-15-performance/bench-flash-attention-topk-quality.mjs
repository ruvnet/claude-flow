#!/usr/bin/env node
/**
 * Dream Cycle 2026-08-15 — DEEP=performance
 *
 * Self-contained, git-reproducible benchmark comparing:
 *   - BASELINE: v3/@claude-flow/neural/src/flash-attention.ts at git HEAD
 *     (hardcoded 12% top-K fraction, no quality metric)
 *   - CANDIDATE: the same file in the working tree (topKFraction configurable,
 *     default still 0.12; benchmark() now also reports RMSE vs exact attention)
 *
 * No npm dependencies. Uses Node's built-in `--experimental-strip-types` to
 * import the .ts source directly (verified on Node v22.22.2). Baseline is
 * extracted live via `git show HEAD:...` so this script self-invalidates if
 * ever run against a tree where HEAD has moved past tonight's commit.
 *
 * Determinism: all Q/K/V test vectors are generated by a seeded mulberry32
 * PRNG defined in *this* script — never by the class's own Math.random()-based
 * generateRandomVectors(), so baseline and candidate see byte-identical
 * inputs and results are reproducible across re-runs.
 *
 * Usage: node bench-flash-attention-topk-quality.mjs [--json-only]
 */

import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const REPO_ROOT = execFileSync('git', ['rev-parse', '--show-toplevel']).toString().trim();
const CANDIDATE_PATH = join(REPO_ROOT, 'v3/@claude-flow/neural/src/flash-attention.ts');
const JSON_ONLY = process.argv.includes('--json-only');

// ----------------------------------------------------------------------------
// Seeded deterministic RNG (mulberry32) — reproducible across runs/machines
// ----------------------------------------------------------------------------
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function makeVectors(count, dim, rng) {
  const out = new Array(count);
  for (let i = 0; i < count; i++) {
    const v = new Float32Array(dim);
    let norm = 0;
    for (let d = 0; d < dim; d++) {
      const x = (rng() - 0.5) * 2;
      v[d] = x;
      norm += x * x;
    }
    norm = Math.sqrt(norm) || 1;
    for (let d = 0; d < dim; d++) v[d] /= norm;
    out[i] = v;
  }
  return out;
}

function rmse(exact, approx) {
  let sumSq = 0, count = 0;
  for (let i = 0; i < exact.length; i++) {
    const e = exact[i], a = approx[i];
    const dim = Math.min(e.length, a.length);
    for (let d = 0; d < dim; d++) {
      const diff = e[d] - a[d];
      sumSq += diff * diff;
      count++;
    }
  }
  return count > 0 ? Math.sqrt(sumSq / count) : 0;
}

function timeMs(fn, iterations) {
  // Warm up once (JIT), then average `iterations` timed calls.
  fn();
  let total = 0;
  for (let i = 0; i < iterations; i++) {
    const start = performance.now();
    fn();
    total += performance.now() - start;
  }
  return total / iterations;
}

// ----------------------------------------------------------------------------
// Extract baseline (git HEAD) into a temp file, import both modules
// ----------------------------------------------------------------------------
const tmpDir = mkdtempSync(join(tmpdir(), 'dream-flash-bench-'));
let BaselineFlashAttention, CandidateFlashAttention, baselineSha, headSha;
try {
  headSha = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: REPO_ROOT }).toString().trim();
  const baselineSrc = execFileSync(
    'git', ['show', `HEAD:v3/@claude-flow/neural/src/flash-attention.ts`],
    { cwd: REPO_ROOT, maxBuffer: 1024 * 1024 * 16 },
  ).toString();
  baselineSha = execFileSync('git', ['hash-object', '--stdin'], { input: baselineSrc }).toString().trim();
  const baselinePath = join(tmpDir, 'flash-attention.baseline.ts');
  writeFileSync(baselinePath, baselineSrc);

  const baselineMod = await import(pathToFileURL(baselinePath).href);
  const candidateMod = await import(pathToFileURL(CANDIDATE_PATH).href + `?t=${Date.now()}`);
  BaselineFlashAttention = baselineMod.FlashAttention;
  CandidateFlashAttention = candidateMod.FlashAttention;
} finally {
  // tmp dir cleaned at the end after both modules are loaded (imports are cached by URL)
}

if (!BaselineFlashAttention || !CandidateFlashAttention) {
  console.error('FATAL: could not import baseline/candidate FlashAttention class');
  process.exit(1);
}

// Sanity: baseline module truly has NO topKFraction config (old hardcoded 0.12 literal)
const baselineHasConfig = Object.prototype.hasOwnProperty.call(
  new BaselineFlashAttention({}).getConfig(), 'topKFraction',
);
if (baselineHasConfig) {
  console.error('FATAL: baseline (git HEAD) unexpectedly already has topKFraction — is HEAD stale vs working tree?');
  process.exit(1);
}

// ----------------------------------------------------------------------------
// Benchmark scenarios — representative of the codebase's actual embedding
// dimension (384, see CLAUDE.md ONNX/all-MiniLM-L6-v2) plus edge cases that
// exercise each of cpuOptimizedAttention's three internal paths.
// ----------------------------------------------------------------------------
const SCENARIOS = [
  { name: 'small (no top-K path, numK<=32)', numQueries: 20, numKeys: 24, dim: 384, iterations: 7 },
  { name: 'boundary-low (buggy range starts, numK=33)', numQueries: 20, numKeys: 33, dim: 384, iterations: 7 },
  { name: 'medium (buggy range, numK=96)', numQueries: 40, numKeys: 96, dim: 384, iterations: 7 },
  { name: 'boundary-high (buggy range ends, numK=128)', numQueries: 40, numKeys: 128, dim: 384, iterations: 7 },
  { name: 'just-above-buggy-range (numK=129, two-stage kicks in)', numQueries: 40, numKeys: 129, dim: 384, iterations: 5 },
  { name: 'large (two-stage screening, numK>128)', numQueries: 100, numKeys: 512, dim: 384, iterations: 5 },
  { name: 'xlarge (two-stage screening, numK>128)', numQueries: 200, numKeys: 2048, dim: 384, iterations: 3 },
];

const results = [];
for (const scenario of SCENARIOS) {
  const rng = mulberry32(0xC0FFEE ^ scenario.numKeys);
  const Q = makeVectors(scenario.numQueries, scenario.dim, rng);
  const K = makeVectors(scenario.numKeys, scenario.dim, rng);
  const V = makeVectors(scenario.numKeys, scenario.dim, rng);

  const baseline = new BaselineFlashAttention({ dimensions: scenario.dim });
  const candidateDefault = new CandidateFlashAttention({ dimensions: scenario.dim }); // topKFraction default 0.12

  const exact = baseline.naiveAttention(Q, K, V); // ground truth, same algorithm in both files

  const baselineFlashTimeMs = timeMs(() => baseline.cpuOptimizedAttention(Q, K, V), scenario.iterations);
  const baselineFlashOutput = baseline.cpuOptimizedAttention(Q, K, V);
  const baselineRmse = rmse(exact, baselineFlashOutput);

  const candidateFlashTimeMs = timeMs(() => candidateDefault.cpuOptimizedAttention(Q, K, V), scenario.iterations);
  const candidateFlashOutput = candidateDefault.cpuOptimizedAttention(Q, K, V);
  const candidateRmse = rmse(exact, candidateFlashOutput);

  const naiveTimeMs = timeMs(() => baseline.naiveAttention(Q, K, V), scenario.iterations);

  // Byte-identical output check: candidate at default settings must match
  // baseline output exactly (same 12% fraction, same algorithm) — this is
  // the "no behavior change by default" regression gate.
  let maxAbsDelta = 0;
  for (let i = 0; i < baselineFlashOutput.length; i++) {
    for (let d = 0; d < baselineFlashOutput[i].length; d++) {
      maxAbsDelta = Math.max(maxAbsDelta, Math.abs(baselineFlashOutput[i][d] - candidateFlashOutput[i][d]));
    }
  }

  const baselineHadNaN = !Number.isFinite(baselineRmse) || baselineFlashOutput.some((v) => v.some((x) => !Number.isFinite(x)));
  const candidateFinite = Number.isFinite(candidateRmse) && candidateFlashOutput.every((v) => v.every((x) => Number.isFinite(x)));

  results.push({
    scenario: scenario.name,
    numQueries: scenario.numQueries,
    numKeys: scenario.numKeys,
    dim: scenario.dim,
    naiveTimeMs: round(naiveTimeMs),
    baseline: { flashTimeMs: round(baselineFlashTimeMs), speedup: round(naiveTimeMs / baselineFlashTimeMs), rmse: baselineRmse, hadNaN: baselineHadNaN },
    candidateAtDefault: { flashTimeMs: round(candidateFlashTimeMs), speedup: round(naiveTimeMs / candidateFlashTimeMs), rmse: candidateRmse, isFinite: candidateFinite },
    maxAbsOutputDelta: maxAbsDelta,
    outputIdenticalAtDefault: maxAbsDelta === 0,
    // Two different pass/fail rules depending on whether this scenario falls
    // in the buggy 32<numK<=128 range:
    //  - baseline NOT NaN (numK<=32 or numK>128): candidate MUST be
    //    byte-identical to baseline (this fix must not touch those paths).
    //  - baseline WAS NaN (32<numK<=128): candidate MUST now be fully finite
    //    and closely track exact attention (this IS the bug being fixed —
    //    divergence from a NaN baseline is the expected, desired outcome).
    scenarioPass: baselineHadNaN ? candidateFinite : maxAbsDelta === 0,
  });
}

function round(n) { return Math.round(n * 10000) / 10000; }

const allPass = results.every((r) => r.scenarioPass);
const bugScenarios = results.filter((r) => r.baseline.hadNaN);
const unaffectedScenarios = results.filter((r) => !r.baseline.hadNaN);

const receipt = {
  hypothesis: 'expBuffer sizing in cpuOptimizedAttention() is keyed off `useTopK` alone but the branch actually taken is keyed off `useTopK && numK > 128`; for 32<numK<=128 this undersizes expBuffer to topK, causing NaN outputs. Fixing the sizing predicate to match the branch predicate should (a) make all outputs finite for 32<numK<=128, with RMSE close to exact attention, and (b) leave numK<=32 and numK>128 paths byte-identical to baseline (no regression).',
  headSha,
  baselineFileBlobSha: baselineSha,
  runtime: `node ${process.version}, --experimental-strip-types (no npm deps)`,
  scenarios: results,
  bugConfirmedInScenarios: bugScenarios.map((r) => r.scenario),
  unaffectedScenariosByteIdentical: unaffectedScenarios.every((r) => r.outputIdenticalAtDefault),
  verdict: allPass
    ? 'ACCEPT: bug reproduced in baseline for 32<numK<=128, fixed (finite + low RMSE) in candidate, zero behavior change outside that range'
    : 'REJECT: candidate did not satisfy the per-scenario pass rule — investigate',
};

if (!JSON_ONLY) {
  console.log('# Flash Attention topK-quality benchmark — Dream Cycle 2026-08-15\n');
  console.log(`HEAD: ${headSha}`);
  console.log(`Baseline file blob sha: ${baselineSha}\n`);
  console.log('| Scenario | numK | naive ms | baseline flash ms | baseline speedup | baseline RMSE | candidate(default) flash ms | candidate speedup | candidate RMSE | max|Δ| output |');
  console.log('|---|---|---|---|---|---|---|---|---|---|');
  for (const r of results) {
    console.log(`| ${r.scenario} | ${r.numKeys} | ${r.naiveTimeMs} | ${r.baseline.flashTimeMs} | ${r.baseline.speedup}x | ${r.baseline.rmse.toExponential(3)} | ${r.candidateAtDefault.flashTimeMs} | ${r.candidateAtDefault.speedup}x | ${r.candidateAtDefault.rmse.toExponential(3)} | ${r.maxAbsOutputDelta} |`);
  }
  console.log(`\nVerdict: ${receipt.verdict}`);
}

console.log('===BENCH_JSON===');
console.log(JSON.stringify(receipt, null, 2));

rmSync(tmpDir, { recursive: true, force: true });
process.exit(allPass ? 0 : 1);
