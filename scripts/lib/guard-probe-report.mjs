// Markdown rendering of a probe run for v3/docs/validation/mod-guard-probe-*.md. Pure: rows in, string out.

const count = (r, s) => r.results.filter(x => x.status === s).length
const worstOf = r => r.results.reduce((m, x) => (x.status === 'skip' || x.ms <= m.ms ? m : x), { ms: 0, id: '-' })
const cell = s => ({ pass: '✓', fail: '✗', info: '~', skip: '·' })[s] ?? '?'

export function renderReport({ rows, args, startedMs }) {
  const out = []
  const ids = [...new Set(rows.flatMap(r => r.results.map(x => x.id)))]
  const byId = id => rows.map(r => [r.name, r.results.find(x => x.id === id)]).filter(([, x]) => x)
  out.push(`Generated by \`node scripts/probe-mod-guards.mjs${args.fast ? ' --fast' : ''}\` in ${((Date.now() - startedMs) / 1000).toFixed(1)}s. Timing: a probe fails only above ${args.budgetMs} ms (median of 3: hang / catastrophic backtracking); ${args.advisoryMs}-${args.budgetMs} ms, or >50x the guard's own trivial-input time, is reported as advisory slow, not failed.`)
  out.push('')
  out.push('## Per-plugin summary')
  out.push('')
  out.push('| plugin | secret surface found (tool[namespace].field) | pass | fail | advisory miss | skipped | worst ms (probe) |')
  out.push('|---|---|---:|---:|---:|---:|---|')
  for (const r of rows) {
    const w = worstOf(r)
    const surface = r.meta.chosen.length ? r.meta.chosen.map(c => `\`${c.at}\``).join('<br>') : r.fatal ? `**FATAL** ${r.fatal}` : 'none (policy guard)'
    out.push(`| ${r.name} | ${surface} | ${count(r, 'pass')} | ${count(r, 'fail')} | ${count(r, 'info')} | ${count(r, 'skip')} | ${w.ms.toFixed(1)} (${w.id}) |`)
  }
  out.push('')
  out.push('## Probe matrix (✓ pass · ✗ fail · ~ advisory miss · · not applicable)')
  out.push('')
  out.push('Columns are plugins in the order of the summary table above (1 = first row).')
  out.push('')
  out.push(`| probe | class | ${rows.map((_, i) => i + 1).join(' | ')} |`)
  out.push(`|---|---|${rows.map(() => ':-:').join('|')}|`)
  for (const id of ids) {
    const hit = byId(id)
    const cls = hit[0]?.[1].cls ?? ''
    const by = new Map(hit)
    out.push(`| ${id} | ${cls} | ${rows.map(r => (by.has(r.name) ? cell(by.get(r.name).status) : '·')).join(' | ')} |`)
  }
  out.push('')
  out.push('## Failures by probe')
  out.push('')
  for (const id of ids) {
    const bad = byId(id).filter(([, x]) => x.status === 'fail' || x.status === 'info')
    if (bad.length === 0) continue
    const tier = bad[0][1].status === 'info' ? 'advisory' : 'must'
    const applicable = byId(id).length
    const clean = byId(id).filter(([, x]) => x.status === 'pass').map(([n]) => n)
    const who = bad.length > applicable / 2 ? `all but ${clean.join(', ') || 'none'}` : bad.map(([n, x]) => `${n}${x.ms > args.budgetMs ? ` ${x.ms.toFixed(0)}ms` : ''}`).join(', ')
    out.push(`- **${id}** (${tier}) — ${bad.length}/${applicable}: ${who}`)
  }
  out.push('')
  return out.join('\n')
}
