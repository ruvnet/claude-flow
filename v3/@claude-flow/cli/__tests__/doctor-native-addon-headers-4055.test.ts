/** #4055: native addons built against Node >=24.19 headers abort on Node 24.19-24.21 (nodejs/node#65446). */
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  checkNativeAddonHeaders,
  headersVersionFromGypi,
  isAffectedNodeVersion,
} from '../src/commands/doctor-native-addon.js';

let root: string;
beforeEach(() => { root = mkdtempSync(join(tmpdir(), 'ruflo-4055-')); });
afterEach(() => { rmSync(root, { recursive: true, force: true }); });

const gypi = (nodedir: string) => `# Do not edit. File was generated by node-gyp's "configure" step
{
  "target_defaults": { "cflags": [], "default_configuration": "Release" },
  "variables": {
    "napi_build_version": "0",
    "nodedir": "${nodedir}",
    "node_module_version": 137
  }
}
`;

function addon(dir: string, version: string, nodedir: string | null) {
  mkdirSync(join(dir, 'build'), { recursive: true });
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ name: 'better-sqlite3', version }));
  if (nodedir !== null) writeFileSync(join(dir, 'build', 'config.gypi'), gypi(nodedir));
}

describe('isAffectedNodeVersion', () => {
  it.each([
    ['24.18.1', false], ['24.19.0', true], ['24.20.1', true], ['24.21.0', true],
    ['24.21.5', true], ['22.23.2', false], ['25.0.0', false], ['20.11.0', false],
  ])('%s -> %s', (v, expected) => expect(isAffectedNodeVersion(v)).toBe(expected));
});

describe('headersVersionFromGypi', () => {
  it('reads the version out of the node-gyp cache nodedir', () => {
    expect(headersVersionFromGypi(gypi('/home/u/.cache/node-gyp/24.20.0'))).toBe('24.20.0');
  });
  it('reads a node-vXX source-tree nodedir', () => {
    expect(headersVersionFromGypi(gypi('/opt/node-v24.21.0'))).toBe('24.21.0');
  });
  it('returns null when no version can be read', () => {
    expect(headersVersionFromGypi(gypi('/usr/include/node'))).toBeNull();
    expect(headersVersionFromGypi('not a gypi')).toBeNull();
  });
});

describe('checkNativeAddonHeaders', () => {
  it('warns for a copy built against 24.20 headers on Node 24.21', async () => {
    const bad = join(root, 'node_modules', 'agentdb', 'node_modules', 'better-sqlite3');
    addon(bad, '11.10.0', '/home/u/.cache/node-gyp/24.20.0');
    const r = await checkNativeAddonHeaders({ nodeVersion: '24.21.0', copies: [bad] });
    expect(r.status).toBe('warn');
    expect(r.message).toContain('11.10.0');
    expect(r.message).toContain('24.20.0');
    expect(r.message).toContain(bad);
    expect(r.fix).toMatch(/24\.18\.1/);
    expect(r.fix).toMatch(/node-gyp rebuild/);
    expect(r.fix).toMatch(/nodedir/);
  });

  it('passes for a prebuilt copy (no config.gypi) on an affected Node', async () => {
    const pre = join(root, 'node_modules', 'better-sqlite3');
    addon(pre, '12.11.1', null);
    const r = await checkNativeAddonHeaders({ nodeVersion: '24.21.0', copies: [pre] });
    expect(r.status).toBe('pass');
  });

  it('passes for a copy rebuilt against 24.18.1 headers', async () => {
    const ok = join(root, 'node_modules', 'better-sqlite3');
    addon(ok, '11.10.0', '/home/u/.cache/node-gyp/24.18.1');
    const r = await checkNativeAddonHeaders({ nodeVersion: '24.21.0', copies: [ok] });
    expect(r.status).toBe('pass');
  });

  it('is not applicable off the affected Node range', async () => {
    const bad = join(root, 'node_modules', 'better-sqlite3');
    addon(bad, '11.10.0', '/home/u/.cache/node-gyp/24.20.0');
    for (const nodeVersion of ['22.23.2', '24.18.1', '25.0.0']) {
      const r = await checkNativeAddonHeaders({ nodeVersion, copies: [bad] });
      expect(r.status).toBe('pass');
      expect(r.message).toMatch(/not affected|not in the affected/i);
    }
  });

  it('reports every bad copy, not just the first', async () => {
    const a = join(root, 'node_modules', 'agentdb', 'node_modules', 'better-sqlite3');
    const b = join(root, 'node_modules', 'agentic-flow', 'node_modules', 'better-sqlite3');
    addon(a, '11.10.0', '/c/node-gyp/24.20.0');
    addon(b, '11.10.0', '/c/node-gyp/24.19.0');
    const r = await checkNativeAddonHeaders({ nodeVersion: '24.20.0', copies: [a, b] });
    expect(r.status).toBe('warn');
    expect(r.message).toContain(a);
    expect(r.message).toContain(b);
  });

  it('discovers nested copies under node_modules by walking up from a start dir', async () => {
    const top = join(root, 'node_modules', 'better-sqlite3');
    const nested = join(root, 'node_modules', 'agentdb', 'node_modules', 'better-sqlite3');
    addon(top, '12.11.1', null);
    addon(nested, '11.10.0', '/c/node-gyp/24.20.0');
    const start = join(root, 'node_modules', '@claude-flow', 'cli', 'dist', 'src', 'commands');
    mkdirSync(start, { recursive: true });
    const r = await checkNativeAddonHeaders({ nodeVersion: '24.21.0', startDirs: [start] });
    expect(r.status).toBe('warn');
    expect(r.message).toContain(nested);
    expect(r.message).not.toContain(`${top} `);
  });

  it('never throws on unreadable or malformed files', async () => {
    const weird = join(root, 'node_modules', 'better-sqlite3');
    mkdirSync(join(weird, 'build'), { recursive: true });
    writeFileSync(join(weird, 'package.json'), '{not json');
    writeFileSync(join(weird, 'build', 'config.gypi'), '\u0000\u0001');
    const r = await checkNativeAddonHeaders({ nodeVersion: '24.21.0', copies: [weird, join(root, 'missing')] });
    expect(['pass', 'warn']).toContain(r.status);
  });
});
